func initUILanguage() {
	pref := "ko"
	if dir, err := os.UserConfigDir(); err == nil {
		if b, e := os.ReadFile(filepath.Join(dir, "dotPaint", "language.txt")); e == nil {
			if x := strings.TrimSpace(string(b)); x == "en" || x == "ko" {
				pref = x
			}
		}
	}
	if x := os.Getenv("DOTPAINT_UI_LANGUAGE"); x == "ko" || x == "en" {
		pref = x
	}
	dotPaintEdition = pref
}
func saveUILanguagePreference(lang string) error {
	if lang != "ko" && lang != "en" {
		return nil
	}
	dir, err := os.UserConfigDir()
	if err != nil {
		return err
	}
	dir = filepath.Join(dir, "dotPaint")
	if err := os.MkdirAll(dir, 0700); err != nil {
		return err
	}
	tmp := filepath.Join(dir, "language.txt.tmp")
	if err := os.WriteFile(tmp, []byte(lang+"\n"), 0600); err != nil {
		return err
	}
	dest := filepath.Join(dir, "language.txt")
	// os.Rename does not replace an existing file on all Windows versions.
	if err := os.Remove(dest); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return os.Rename(tmp, dest)
}
func localizeUI(s string) string {
	if dotPaintEdition != "en" || s == "" {
		return s
	}
	if out, ok := uiTranslations[s]; ok {
		return out
	}
	return localizeTemplatedUI(s)
}
func internalUIValue(s string) string {
	if dotPaintEdition != "en" {
		return s
	}
	// Stable Korean internal script IDs: never let translated combobox labels
	// change internal text renderer semantics.
	switch s {
	case "Latin":
		return "영문"
	case "Korean":
		return "한글"
	case "None":
		return "없음"
	case "Numbers / Symbols":
		return "숫자·기호"
	}
	uiReverseOnce.Do(func() {
		uiReverse = make(map[string]string, len(uiTranslations))
		for ko, en := range uiTranslations {
			if _, exists := uiReverse[en]; !exists {
				uiReverse[en] = ko
			}
		}
	})
	if orig, exists := uiReverse[s]; exists {
		return orig
	}
	return s
}

